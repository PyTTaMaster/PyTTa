"""
Tests for pytta.smooth_frequency.

Each test pins one rule. The spectra are built directly in the frequency
domain, so the input magnitude is known bin by bin. The last test compares
the whole thing with the ITA-Toolbox (RWTH Aachen) on data generated by
golden/make_smooth_frequency_ita.m.

The smoothing is a moving average over a logarithmic frequency grid of
1 cent, 1200 / nthOct cents wide, applied to the magnitude of freqSignal;
the phase is kept. The grid runs 20 octaves below Nyquist, so the first
bins take part through linear interpolation from DC.
"""
import os
import unittest

import numpy as np
import scipy.io as sio

import pytta

GOLDEN = os.path.join(os.path.dirname(__file__), 'golden',
                      'smooth_frequency_ita.mat')
FS = 48000
N = 2048
K = N // 2 + 1
TOL32 = 1e-6  # rounding of the complex64 freqSignal storage


# SignalObj built from a half spectrum of K rows. Built inline in each test:
# SignalObj inspects the caller's frame (classes/_instanceinfo.py) and fails
# when the caller's first local variable is an array.
FREQ = dict(samplingRate=FS, numSamples=N, signalType='power')


def cents(k, k0):
    """Distance in cents from bin k0 to bin k."""
    return 1200 * np.log2(k / k0)


class TestSmoothFrequency(unittest.TestCase):

    def test_constant_magnitude_keeps_spectrum_and_phase(self):
        # A flat magnitude is its own moving average on any grid, and the
        # phase is not touched: the output equals the input, bin by bin.
        rng = np.random.default_rng(1)
        phase = rng.uniform(-np.pi, np.pi, K)
        phase[0] = phase[-1] = 0
        spec = 0.3 * np.exp(1j * phase)
        out = pytta.smooth_frequency(pytta.SignalObj(spec, 'freq', **FREQ), nthOct=3)
        worst = np.max(np.abs(out.freqSignal[:, 0] - spec)) / 0.3
        print(f'\n  flat spectrum, worst rel change = {worst:.2e}')
        self.assertLess(worst, TOL32)

    def test_single_bin_spreads_into_a_flat_band_of_the_given_width(self):
        # One bin at k0 = 100 is, on the cent grid, a triangle of base
        # 1200 log2(101/99) ~ 34.6 cents and height 1. A box average of
        # w cents turns it into a plateau of height area / w wherever the
        # box holds the whole triangle: inside +-(h - 18) cents of k0, with
        # h = (w - 1) / 2, and zero beyond +-(h + 18) cents. w is
        # round(1200 / nthOct) made odd: 1199, 399 and 99 cents.
        k0 = 100
        spec = np.zeros(K, dtype=complex)
        spec[k0] = 1j  # phase pi/2: the magnitude is read back below
        area = 600 * np.log2((k0 + 1) / (k0 - 1))
        k = np.arange(1, K)
        for nthOct, w in [(1, 1199), (3, 399), (12, 99)]:
            out = pytta.smooth_frequency(pytta.SignalObj(spec, 'freq', **FREQ),
                                         nthOct=nthOct)
            y = np.abs(out.freqSignal[1:, 0])
            h = (w - 1) / 2
            inside = np.abs(cents(k, k0)) <= h - 40
            outside = np.abs(cents(k, k0)) >= h + 40
            plateau = y[inside]
            flat = np.ptp(plateau) / plateau.mean()
            err = plateau.mean() / (area / w) - 1
            leak = np.max(np.abs(y[outside])) / plateau.mean()
            print(f'\n  1/{nthOct} oct: {inside.sum()} bins on plateau, '
                  f'flatness {flat:.1e}, height err {err:+.3f}, leak {leak:.1e}')
            self.assertLess(flat, 10 * TOL32)
            self.assertLess(abs(err), 0.03)
            self.assertLess(leak, TOL32)
            self.assertEqual(out.freqSignal[0, 0], 0)

    def test_dc_and_nyquist_bins_are_kept(self):
        # DC is copied through. At Nyquist the box shrinks to one grid
        # point, so the magnitude there is also unchanged.
        rng = np.random.default_rng(2)
        spec = rng.standard_normal(K) + 1j * rng.standard_normal(K)
        spec[0] = 2.0
        spec[-1] = -1.5
        out = pytta.smooth_frequency(pytta.SignalObj(spec, 'freq', **FREQ), nthOct=1)
        self.assertAlmostEqual(out.freqSignal[0, 0], 2.0, delta=TOL32)
        self.assertAlmostEqual(out.freqSignal[-1, 0], -1.5, delta=TOL32)

    def test_returns_new_object_and_smooths_channels_independently(self):
        rng = np.random.default_rng(3)
        sig = pytta.SignalObj(rng.standard_normal((N, 2)), 'time', FS)
        before = sig.freqSignal.copy()
        out = pytta.smooth_frequency(sig, nthOct=3)
        self.assertTrue(np.array_equal(sig.freqSignal, before))
        self.assertIsNot(out, sig)
        self.assertEqual(out.samplingRate, FS)
        self.assertEqual(out.numSamples, N)
        self.assertEqual(out.numChannels, 2)
        single = pytta.smooth_frequency(
            pytta.SignalObj(sig.timeSignal[:, 1], 'time', FS), nthOct=3)
        worst = (np.max(np.abs(out.freqSignal[:, 1] - single.freqSignal[:, 0]))
                 / np.max(np.abs(single.freqSignal)))
        self.assertLess(worst, TOL32)

    def test_rejects_invalid_arguments(self):
        sig = pytta.SignalObj(np.ones(N), 'time', FS)
        with self.assertRaises(ValueError):
            pytta.smooth_frequency(sig, nthOct=0)
        with self.assertRaises(ValueError):
            pytta.smooth_frequency(sig, nthOct=-3)
        with self.assertRaises(TypeError):
            pytta.smooth_frequency(np.ones(N), nthOct=3)

    def test_matches_ita_toolbox(self):
        # Sample by sample against ita_smooth_frequency on the stored
        # signal, at 1, 1/3 and 1/12 octave. PyTTa and ITA scale the AC
        # bins by different constants, measured here from the two input
        # spectra (the signal has zero DC and Nyquist, see the generator).
        self.assertTrue(os.path.exists(GOLDEN),
                        'run golden/make_smooth_frequency_ita.m')
        g = sio.loadmat(GOLDEN, squeeze_me=True, struct_as_record=False)
        sig = pytta.SignalObj(g['x'], 'time', int(g['fs']))
        ratio = np.abs(g['freqDataIn'][1:-1]) / np.abs(sig.freqSignal[1:-1])
        self.assertLess(np.ptp(ratio) / ratio.mean(), TOL32,
                        'input spectra are not one scale apart')
        scale = ratio.mean()
        for case in np.atleast_1d(g['cases']):
            out = pytta.smooth_frequency(sig, nthOct=int(case.nthOct))
            peak = np.max(np.abs(case.freqData))
            diff = np.max(np.abs(out.freqSignal * scale - case.freqData)) / peak
            print(f'\n  1/{int(case.nthOct):<2d} oct: rel peak diff vs ITA = '
                  f'{diff:.2e} (tol {TOL32})')
            self.assertLess(diff, TOL32)


if __name__ == '__main__':
    unittest.main()
