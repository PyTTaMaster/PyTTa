"""
Tests for pytta.time_window.

Each test pins one rule of the function. The shape rules are checked on a
signal of ones, so the output is the window itself. The last test compares
the whole thing with the ITA-Toolbox (RWTH Aachen) on data generated by
golden/make_time_window_ita.m.

Index convention: an interval is a list of [start, end] pairs. start <= end
is a falling slope (ones before start, zeros after end); start > end is a
rising slope (zeros before end, ones after start). Both bounds belong to the
slope, which therefore has abs(end - start) + 1 samples.
"""
import os
import unittest

import numpy as np
import scipy.io as sio

import pytta

GOLDEN = os.path.join(os.path.dirname(__file__), 'golden', 'time_window_ita.mat')
FS = 1000
N = 1000
TOL32 = 1e-6  # rounding of the float32 SignalObj storage


def ones(numChannels=1):
    return pytta.SignalObj(np.ones((N, numChannels)), 'time', FS)


def window_of(interval, **kwargs):
    """Apply time_window to ones and return the resulting window, 1-D."""
    out = pytta.time_window(ones(), interval, unit='samples', **kwargs)
    return out.timeSignal[:, 0].astype(float)


class TestTimeWindow(unittest.TestCase):

    def test_falling_slope_is_hann_half_between_bounds(self):
        # [200, 399]: 200 ones, then the falling half of hann(400), i.e.
        # 0.5 * (1 - cos(2 pi k / 399)) for k = 200..399, then zeros.
        # The slope ends at exactly 0 (symmetric hann, not hanning).
        s, e = 200, 399
        w = window_of([s, e])
        L = e - s + 1
        k = np.arange(L, 2 * L)
        expected = 0.5 * (1 - np.cos(2 * np.pi * k / (2 * L - 1)))
        worst = np.max(np.abs(w[s:e + 1] - expected))
        print(f'\n  falling slope vs analytic hann, worst={worst:.2e} (tol {TOL32})')
        self.assertTrue(np.all(w[:s] == 1))
        self.assertLess(worst, TOL32)
        self.assertEqual(w[e], 0)
        self.assertTrue(np.all(w[e + 1:] == 0))

    def test_rising_slope_mirrors_falling(self):
        # start > end reverses the slope: zeros, rise, ones. It must be the
        # sample-by-sample mirror of the falling window on mirrored indices.
        rising = window_of([600, 450])
        falling = window_of([N - 1 - 600, N - 1 - 450])
        self.assertTrue(np.array_equal(rising, falling[::-1]))

    def test_pairs_compose_by_product(self):
        # Two pairs are two windows multiplied, independent of order.
        both = window_of([120, 0, 800, 999])
        rise = window_of([120, 0])
        fall = window_of([800, 999])
        self.assertTrue(np.allclose(both, rise * fall, atol=TOL32))
        self.assertTrue(np.array_equal(both, window_of([800, 999, 120, 0])))

    def test_rect_window_is_hard_cut(self):
        # A rectangular window keeps the slope at 1: a cut right after end.
        w = window_of([300, 499], window='rect')
        self.assertTrue(np.all(w[:500] == 1))
        self.assertTrue(np.all(w[500:] == 0))

    def test_time_unit_rounds_to_nearest_sample(self):
        # Seconds are converted with round(t * fs), halves up. 0.2004 s at
        # 1 kHz is sample 200, 0.3995 s is sample 400 (not 399). No further
        # adjustment of the bounds (the ITA-Toolbox moves them to even
        # numbers; this implementation does not).
        inSeconds = pytta.time_window(ones(), [0.2004, 0.3995], unit='time')
        inSamples = pytta.time_window(ones(), [200, 400], unit='samples')
        self.assertTrue(np.array_equal(inSeconds.timeSignal, inSamples.timeSignal))

    def test_symmetric_mirrors_window_about_centre(self):
        # symmetric=True adds the window to its reverse and removes the
        # offset: for a falling slope in the first half it yields
        # ones, fall, zeros, rise, ones, symmetric about the centre.
        s, e = 300, 499
        w = window_of([s, e], symmetric=True)
        self.assertTrue(np.array_equal(w, w[::-1]))
        self.assertTrue(np.all(w[:s] == 1))
        self.assertEqual(w[e], 0)
        self.assertEqual(w[N // 2], 0)

    def test_returns_new_object_and_keeps_metadata(self):
        # The input is not modified; the output keeps sampling rate and
        # channel count and windows every channel the same way.
        sig = pytta.SignalObj(np.random.default_rng(0).standard_normal((N, 3)),
                              'time', FS)
        before = sig.timeSignal.copy()
        out = pytta.time_window(sig, [0.1, 0.4])
        self.assertTrue(np.array_equal(sig.timeSignal, before))
        self.assertIsNot(out, sig)
        self.assertEqual(out.samplingRate, FS)
        self.assertEqual(out.numChannels, 3)
        w = window_of([100, 400])
        for ch in range(3):
            self.assertTrue(np.allclose(out.timeSignal[:, ch],
                                        before[:, ch] * w, atol=TOL32))

    def test_rejects_invalid_interval(self):
        with self.assertRaises(ValueError):
            pytta.time_window(ones(), [100, 200, 300], unit='samples')  # odd
        with self.assertRaises(ValueError):
            pytta.time_window(ones(), [100, N], unit='samples')  # past end
        with self.assertRaises(ValueError):
            pytta.time_window(ones(), [0.1, 0.2], unit='seconds')  # unknown
        with self.assertRaises(ValueError):
            pytta.time_window(ones(), [100, 200], unit='samples', window='no')

    def test_matches_ita_toolbox(self):
        # Sample-by-sample against ita_time_window on the stored signal, all
        # five cases of golden/make_time_window_ita.m. Intervals there are
        # 1-based MATLAB samples; subtract 1. Tolerance is the float32
        # storage of SignalObj relative to the signal peak.
        self.assertTrue(os.path.exists(GOLDEN), 'run golden/make_time_window_ita.m')
        g = sio.loadmat(GOLDEN, squeeze_me=True, struct_as_record=False)
        x, fs = g['x'], int(g['fs'])
        sig = pytta.SignalObj(x, 'time', fs)
        peak = np.max(np.abs(x))
        for case in np.atleast_1d(g['cases']):
            interval = (np.atleast_1d(case.interval) - 1).tolist()
            window = {'hann': 'hann', 'rectwin': 'rect'}[case.window]
            out = pytta.time_window(sig, interval, unit='samples',
                                    window=window, symmetric=bool(case.symmetric))
            diff = np.max(np.abs(out.timeSignal - case.y)) / peak
            print(f'\n  {case.name:16s} rel peak diff vs ITA = {diff:.2e} (tol {TOL32})')
            self.assertLess(diff, TOL32, case.name)


if __name__ == '__main__':
    unittest.main()
