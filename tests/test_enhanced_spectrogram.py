"""
Tests for pytta.enhanced_spectrogram.

The enhanced spectrogram is the geometric mean of nine reassigned
spectrograms with Blackman-Harris windows of 8 to 512 ms, smoothed
('readable' or 'sharp'), on a logarithmic frequency grid, in dB re the
channel's dBRef (20 uPa for a channel in Pa). Each test pins one rule. The
first compares the whole method with SQAT_GUI_enhanced_stft of SQAT on data
generated by golden/make_enhanced_spectrogram_sqat.m.
"""
import os
import unittest

os.environ.setdefault("MPLBACKEND", "Agg")

import numpy as np
import scipy.io as sio

import pytta

GOLDEN = os.path.join(os.path.dirname(__file__), 'golden',
                      'enhanced_spectrogram_sqat.mat')
FS = 16000


def in_pascal(signalObj):
    for ch in signalObj.channels.mapping:
        signalObj.channels[ch].unit = 'Pa'
    return signalObj


def tone(freq, rms, seconds):
    tt = np.arange(int(seconds * FS)) / FS
    return rms * np.sqrt(2) * np.sin(2 * np.pi * freq * tt)


class TestEnhancedSpectrogram(unittest.TestCase):

    def test_matches_sqat(self):
        # Against SQAT on the stored signal, both smoothings, default grid:
        # t and f whole, the maps on every 16th row and 10th column. Both
        # sides compute in double from the same float32 samples, so the
        # tolerance is far below any visible change and far above the
        # differences of FFT summation order (measured: ~4e-10 dB).
        self.assertTrue(os.path.exists(GOLDEN),
                        'run golden/make_enhanced_spectrogram_sqat.m')
        g = sio.loadmat(GOLDEN, squeeze_me=True)
        sig = in_pascal(pytta.SignalObj(g['x'], 'time', int(g['fs'])))
        rows = np.atleast_1d(g['rows']) - 1
        cols = np.atleast_1d(g['cols']) - 1
        for smoothing in ('readable', 'sharp'):
            t, f, L = pytta.enhanced_spectrogram(sig, smoothing=smoothing)
            self.assertLess(np.max(np.abs(t - g['t'])), 1e-12)
            self.assertLess(np.max(np.abs(f / g['f'] - 1)), 1e-12)
            ref = g['L_' + smoothing]
            got = L[np.ix_(rows, cols)][:, :, 0]
            diff = np.max(np.abs(got - ref))
            print(f'\n  {smoothing:8s} max |dL| vs SQAT = {diff:.2e} dB '
                  f'on {ref.size} cells (tol 1e-6)')
            self.assertLess(diff, 1e-6)

    def test_steady_tone_column_adds_up_to_its_level(self):
        # The cells of a column hold mean square pressure, so a column in the
        # middle of a 94 dB SPL tone (1 Pa rms) adds up to 94 dB. Predicted
        # before running: every window reassigns a steady tone to its true
        # frequency, so the nine maps agree and the geometric mean keeps the
        # energy; within 0.2 dB with either smoothing (measured: 93.94 dB
        # readable, 94.06 dB sharp).
        sig = in_pascal(pytta.SignalObj(tone(1000, 1.0, 1.0), 'time', FS))
        for smoothing in ('readable', 'sharp'):
            t, f, L = pytta.enhanced_spectrogram(sig, smoothing=smoothing)
            column = L[:, len(t) // 2, 0]
            level = 10 * np.log10(np.sum(10 ** (column / 10)))
            print(f'\n  {smoothing:8s} column level = {level:.2f} dB SPL')
            self.assertLess(abs(level - 94), 0.2)

    def test_tone_and_click_land_where_they_are(self):
        # A 1 kHz tone peaks on the frequency row nearest 1 kHz, and a click
        # at 0.5 s peaks within one column (1 ms) of 0.5 s on a row at 4 kHz.
        sig = in_pascal(pytta.SignalObj(tone(1000, 0.1, 1.0), 'time', FS))
        t, f, L = pytta.enhanced_spectrogram(sig, smoothing='sharp')
        peak = f[np.argmax(L[:, len(t) // 2, 0])]
        self.assertEqual(peak, f[np.argmin(np.abs(np.log2(f / 1000)))])
        click = np.zeros(FS)
        click[FS // 2] = 1
        sig = in_pascal(pytta.SignalObj(click, 'time', FS))
        t, f, L = pytta.enhanced_spectrogram(sig, smoothing='sharp')
        row = np.argmin(np.abs(np.log2(f / 4000)))
        self.assertLessEqual(abs(t[np.argmax(L[row, :, 0])] - 0.5), 1e-3)

    def test_silence_sits_at_the_floor(self):
        # log of an empty map: every cell at -120 dB, no NaN or -inf.
        sig = pytta.SignalObj(np.zeros(FS // 4), 'time', FS)
        t, f, L = pytta.enhanced_spectrogram(sig)
        self.assertTrue(np.all(L == -120))

    def test_channels_are_independent_and_input_is_kept(self):
        rng = np.random.default_rng(0)
        data = np.column_stack([tone(500, 0.1, 0.5),
                                0.05 * rng.standard_normal(FS // 2)])
        sig = in_pascal(pytta.SignalObj(data, 'time', FS))
        before = sig.timeSignal.copy()
        t, f, L = pytta.enhanced_spectrogram(sig)
        self.assertTrue(np.array_equal(sig.timeSignal, before))
        self.assertEqual(L.shape, (f.size, t.size, 2))
        single = in_pascal(pytta.SignalObj(sig.timeSignal[:, 1], 'time', FS))
        _, _, L1 = pytta.enhanced_spectrogram(single)
        self.assertTrue(np.array_equal(L[:, :, 1], L1[:, :, 0]))

    def test_plot_shows_the_enhanced_map(self):
        # plot_spectrogram(enhanced=...) draws exactly the map of
        # enhanced_spectrogram, on a logarithmic frequency axis.
        sig = in_pascal(pytta.SignalObj(tone(1000, 0.1, 0.5), 'time', FS))
        figs = pytta.plot_spectrogram(sig, enhanced='sharp', decimalSep='.')
        ax = figs[0].axes[0]
        _, _, L = pytta.enhanced_spectrogram(sig, smoothing='sharp')
        drawn = np.asarray(ax.collections[0].get_array()).reshape(L.shape[:2])
        self.assertTrue(np.array_equal(drawn, L[:, :, 0]))
        self.assertEqual(ax.get_yscale(), 'log')
        figs[0].clf()

    def test_rejects_invalid_arguments(self):
        sig = pytta.SignalObj(np.zeros(FS // 4), 'time', FS)
        with self.assertRaises(ValueError):
            pytta.enhanced_spectrogram(sig, f_min=FS / 2)
        with self.assertRaises(ValueError):
            pytta.enhanced_spectrogram(sig, smoothing='blurry')
        with self.assertRaises(TypeError):
            pytta.enhanced_spectrogram(np.zeros(FS), smoothing='sharp')


if __name__ == '__main__':
    unittest.main()
