"""
Tests for pytta.loudspeaker.

Each test pins one rule. The impedance curves are synthesized from known
parameters, so every estimate has an exact target; the only error left is
the interpolation between frequency bins. The last but one test compares
with the ITA-Toolbox (RWTH Aachen) on data generated by
golden/make_thiele_small_ita.m.

The lumped model is the one of Thiele (1971) and Small (1972):

    Z = Re + j w Le + Bl^2 / (Rms + j w Mms + 1 / (j w Cms)),

and its electrical form, the one impedance_model takes,

    Z = Re + j w Le + Re (Qms / Qes) / (1 + j Qms (f / fs - fs / f)),

with fs = 1 / (2 pi sqrt(Mms Cms)), Qms = 2 pi fs Mms / Rms and
Qes = 2 pi fs Mms Re / Bl^2.
"""
import os
import unittest

import numpy as np
import scipy.io as sio

import pytta
from pytta import loudspeaker

GOLDEN = os.path.join(os.path.dirname(__file__), 'golden',
                      'thiele_small_ita.mat')
FREQ = np.arange(1, 4001) * 0.05  # 0.05 Hz to 200 Hz, 0.05 Hz step
FREQ = np.concatenate([FREQ, np.arange(201, 20001, 1.0)])
C, RHO = 343.2, 1.204  # the module defaults
TOL = 1e-5  # linear interpolation between 0.05 Hz bins


def mechanical(f, Re, Mms, Cms, Rms, Bl, Le=0.0):
    """Electrical impedance of the mechanical circuit, written directly."""
    jw = 2j * np.pi * f
    return Re + jw * Le + Bl**2 / (Rms + jw * Mms + 1 / (jw * Cms))


def rel(a, b):
    return abs(a / b - 1)


class TestThieleSmall(unittest.TestCase):

    def test_impedance_method_recovers_the_small_signal_parameters(self):
        # fs, Qms and Qes from the peak and the two frequencies where
        # |Z| = sqrt(Rmax Re) (Small 1972; Beranek and Mellow 2012, 6.58 and
        # 6.59). With Le = 0 the method is exact, and Re is the minimum of
        # the real part below fs, reached at the lowest frequency.
        true = dict(Re=6.2, fs=48.0, Qms=4.5, Qes=0.45)
        z = loudspeaker.impedance_model(true, FREQ)
        est = loudspeaker.thiele_small((FREQ, z))
        true['Qts'] = true['Qms'] * true['Qes'] / (true['Qms'] + true['Qes'])
        print()
        for key in true:
            print(f'  {key}: true {true[key]:.6g}, estimated {est[key]:.6g}, '
                  f'rel diff {rel(est[key], true[key]):.1e}')
            self.assertLess(rel(est[key], true[key]), TOL, key)
        for key in ('Le', 'Mms', 'Cms', 'Rms', 'Bl', 'Vas'):
            self.assertNotIn(key, est)

    def test_added_mass_gives_the_mechanical_parameters(self):
        # Mms = dm / ((fs / fs')^2 - 1), Cms = 1 / ((2 pi fs)^2 Mms),
        # Rms = 2 pi fs Mms / Qms, Bl^2 = 2 pi fs Mms Re / Qes and
        # Vas = rho c^2 Sd^2 Cms (Beranek and Mellow 2012, 6.66 and 6.27).
        # Both curves come from the mechanical circuit, so this also pins
        # the electrical form against it.
        true = dict(Re=5.6, Mms=0.0215, Cms=9.0e-4, Rms=1.6, Bl=7.3)
        dm, area = 0.015, 0.0201
        z = mechanical(FREQ, **true)
        zm = mechanical(FREQ, **dict(true, Mms=true['Mms'] + dm))
        est = loudspeaker.thiele_small((FREQ, z), Re=true['Re'], area=area,
                                       added_mass=dm,
                                       impedance_with_mass=(FREQ, zm))
        true['Vas'] = RHO * C**2 * area**2 * true['Cms']
        print()
        for key in ('Mms', 'Cms', 'Rms', 'Bl', 'Vas'):
            print(f'  {key}: true {true[key]:.6g}, estimated {est[key]:.6g}, '
                  f'rel diff {rel(est[key], true[key]):.1e}')
            self.assertLess(rel(est[key], true[key]), TOL, key)

    def test_added_volume_gives_vas_and_the_mechanical_parameters(self):
        # In a closed box of volume Vb the compliance becomes Cms Cmb /
        # (Cms + Cmb), with Cmb = Vb / (rho c^2 Sd^2), and
        # Vas = Vb (fc Qec / (fs Qes) - 1) (Small 1972; Beranek and Mellow
        # 2012, 6.69 and 6.72). With Sd the rest follows as above.
        true = dict(Re=7.1, Mms=0.0098, Cms=1.1e-3, Rms=0.9, Bl=5.2)
        vb, area = 0.008, 0.0133
        cmb = vb / (RHO * C**2 * area**2)
        z = mechanical(FREQ, **true)
        zb = mechanical(FREQ, **dict(true, Cms=true['Cms'] * cmb
                                     / (true['Cms'] + cmb)))
        est = loudspeaker.thiele_small((FREQ, z), Re=true['Re'], area=area,
                                       added_volume=vb,
                                       impedance_in_box=(FREQ, zb))
        true['Vas'] = RHO * C**2 * area**2 * true['Cms']
        print()
        for key in ('Vas', 'Mms', 'Cms', 'Rms', 'Bl'):
            print(f'  {key}: true {true[key]:.6g}, estimated {est[key]:.6g}, '
                  f'rel diff {rel(est[key], true[key]):.1e}')
            self.assertLess(rel(est[key], true[key]), TOL, key)

    def test_fit_recovers_the_voice_coil_inductance(self):
        # A voice coil inductance tilts the peak and moves the sqrt(Rmax Re)
        # points, so the closed form is biased. The least squares fit of the
        # model on the whole curve returns Le and removes that bias. At
        # 20 kHz |Z| = 150 ohm, above the resonance peak of 67 ohm, so the
        # peak search must skip the inductive rise.
        true = dict(Re=3.4, Le=1.2e-3, fs=31.0, Qms=6.0, Qes=0.32)
        z = loudspeaker.impedance_model(true, FREQ)
        closed = loudspeaker.thiele_small((FREQ, z))
        est = loudspeaker.thiele_small((FREQ, z), fit=True)
        print()
        for key in true:
            bias = rel(closed[key], true[key]) if key in closed else np.nan
            print(f'  {key}: true {true[key]:.6g}, fitted {est[key]:.6g}, '
                  f'rel diff {rel(est[key], true[key]):.1e} '
                  f'(closed form {bias:.1e})')
            self.assertLess(rel(est[key], true[key]), 1e-6, key)

    def test_parity_with_ita_thiele_small(self):
        # ita_linear_loudspeaker builds the curves on an FFT grid of
        # 44100 / 2^18 = 0.168 Hz and ita_thiele_small reads them bin by bin
        # (resonance at the bin where the phase changes sign, bandwidth at
        # the first and last bins above Rp / sqrt(2)), so its estimates are
        # off by up to a few bins. The model must match to rounding; the
        # estimates within 1 %.
        g = sio.loadmat(GOLDEN, squeeze_me=True)
        Re, Mms, Cms, Rms, Bl = (float(g[k]) for k in
                                 ('Re', 'Mms', 'Cms', 'Rms', 'Bl'))
        ws = 1 / np.sqrt(Mms * Cms)
        params = dict(Re=Re, fs=ws / (2 * np.pi), Qms=ws * Mms / Rms,
                      Qes=ws * Mms * Re / Bl**2)
        Qts = params['Qms'] * params['Qes'] / (params['Qms'] + params['Qes'])
        model = loudspeaker.impedance_model(params, g['freqSample'])
        err = np.max(np.abs(model - g['zSample']) / np.abs(g['zSample']))
        print(f'\n  impedance model vs ita_linear_loudspeaker: {err:.1e}')
        self.assertLess(err, 1e-12)

        sr, n = int(g['sr']), 2 ** int(g['fftDegree'])
        f = np.fft.rfftfreq(n, 1 / sr)
        dm, area = float(g['dm']), np.pi * float(g['d'])**2 / 4
        z = mechanical(f[1:], Re, Mms, Cms, Rms, Bl)
        zm = mechanical(f[1:], Re, Mms + dm, Cms, Rms, Bl)
        z = pytta.SignalObj(np.r_[Re, z], 'freq', samplingRate=sr,
                            signalType='energy')
        zm = pytta.SignalObj(np.r_[Re, zm], 'freq', samplingRate=sr,
                             signalType='energy')
        est = loudspeaker.thiele_small(z, area=area, added_mass=dm,
                                       impedance_with_mass=zm,
                                       c=float(g['c']), rho=float(g['rho0']))
        ita = g['ita']
        true = dict(params, Mms=Mms, Cms=Cms, Rms=Rms, Bl=Bl, Qts=Qts,
                    Vas=float(g['rho0']) * float(g['c'])**2 * area**2 * Cms)
        print()
        for key in ('fs', 'Re', 'Qms', 'Qes', 'Qts', 'Mms', 'Cms', 'Rms',
                    'Bl', 'Vas'):
            d = rel(est[key], float(ita[key]))
            t = rel(est[key], true[key]) if key in true else np.nan
            print(f'  {key}: ITA {float(ita[key]):.6g}, PyTTa {est[key]:.6g}, '
                  f'rel diff {d:.1e} (PyTTa vs true {t:.1e})')
            self.assertLess(d, 1e-2, key)

    def test_rejects_invalid_input(self):
        true = dict(Re=6.2, fs=48.0, Qms=4.5, Qes=0.45)
        z = loudspeaker.impedance_model(true, FREQ)
        above = FREQ > 60  # the peak falls at the lower band edge
        with self.assertRaises(ValueError):
            loudspeaker.thiele_small((FREQ[above], z[above]))
        with self.assertRaises(ValueError):  # curve without its mass
            loudspeaker.thiele_small((FREQ, z), impedance_with_mass=(FREQ, z))
        higher = loudspeaker.impedance_model(dict(true, fs=60.0), FREQ)
        with self.assertRaises(ValueError):  # added mass raised fs
            loudspeaker.thiele_small((FREQ, z), added_mass=0.01,
                                     impedance_with_mass=(FREQ, higher))


if __name__ == '__main__':
    unittest.main()
